import { buildModel, fx, label, ordinal, pct, TARGETS, type Model, type Summary } from './model';

const table = (head: string[], rows: (string | number)[][]) =>
  [
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');

export function renderMarkdown(s: Summary): string {
  const m = buildModel(s);
  const out: string[] = [];
  const P = (x: string) => out.push(x, '');
  P('# Doorway — what the bots found');
  P(
    `_Generated by \`pnpm sim:report\` from \`reports/data/summary.json\` (${new Date(s.generatedAt).toISOString().slice(0, 16).replace('T', ' ')} UTC). Ruleset \`${s.ruleset.id}\` (hash \`${s.ruleset.hash.slice(0, 12)}\`), cards hash \`${s.cardsHash.slice(0, 12)}\`. ${m.totals.games.toLocaleString()} simulated games: ${Object.entries(
      m.totals.byStudy,
    )
      .map(([k, v]) => `${k} ${(v as number).toLocaleString()}`)
      .join(', ')}._`,
  );
  P('## Plain-language answers');
  P(
    answers(m)
      .map((a) => `- **${a.q}** ${a.a}`)
      .join('\n'),
  );

  // 1 — headline
  P('## 1. Does arriving first make the Doorway irrelevant?');
  P(headline(m));
  for (const d of m.doorway)
    P(
      `**${d.players} players** — non-first arrivals lose ${fx(d.nonFirstLost)} discs on average; ${pct(d.shareLostAny)} of all arrivals lose at least one.\n\n` +
        table(
          ['Arrival', 'Allowance (avg)', 'Tower at arrival', 'Kept', 'Discs lost (sd)', 'Lose any disc'],
          d.rows.map((r: any) => [
            ordinal(r.order),
            fx(r.allowance, 2),
            `${fx(r.tower, 2)} (sd ${fx(r.towerSd, 1)})`,
            fx(r.kept, 2),
            `${fx(r.lost, 2)} (${fx(r.lostSd, 1)})`,
            pct(r.shareLostAny),
          ]),
        ),
    );
  P(
    `Spec target: non-first arrivals lose ≥ ${TARGETS.nonFirstLost} discs on average → **${fx(m.nonFirstAll)} across 2–4p: ${m.nonFirstAll >= TARGETS.nonFirstLost ? 'pass' : 'fail'}**. Data: S1 (2p) and S2 (3p, 4p).`,
  );

  // 2 — win rates
  P('## 2. Win rate by strategy');
  P(
    'Shared wins count 1/k (R28). Intervals are Wilson 95% CIs over player-games. S2 seats every combination of distinct strategies in every seat order; S1 is the 2p round robin (mirrors included).',
  );
  for (const n of [4, 3, 2]) {
    const g = s.groups[`main-${n}p`];
    if (!g) continue;
    P(
      `**${n} players** (fair share ${pct(1 / n)}):\n\n` +
        table(
          ['Strategy', 'Win rate', '95% CI', 'Mean score (sd)', 'Rushes', 'Discs lost', 'Extra turns'],
          Object.entries(g.byPolicy).map(([id, p]: [string, any]) => [
            label(s, id),
            pct(p.win),
            `[${pct(p.lo)}, ${pct(p.hi)}]`,
            `${fx(p.score.mean, 1)} (${fx(p.score.sd, 1)})`,
            fx(p.rushes),
            fx(p.lost),
            fx(p.extraTurns),
          ]),
        ),
    );
  }
  P(
    `**Dominance check (spec: no archetype above 35% in 4p):** ${m.topArch4 ? `the best archetype, ${m.topArch4.label}, wins ${pct(m.topArch4.win)} [${pct(m.topArch4.lo)}, ${pct(m.topArch4.hi)}] → ${m.topArch4.win <= TARGETS.maxStrategyWin4p ? 'pass' : 'fail'}.` : 'no 4p data.'}${m.look4 ? ` The lookahead search bot (not an archetype) wins ${pct(m.look4.win)} [${pct(m.look4.lo)}, ${pct(m.look4.hi)}] → ${m.look4.win <= TARGETS.maxStrategyWin4p ? 'also under' : 'over'} the ceiling on the stricter reading.` : ''}`,
  );
  if (m.noisy)
    P(
      '**Noisy field (S3, every strategy at ε 0.1, 4p):**\n\n' +
        table(
          ['Strategy', 'Win rate', '95% CI', 'Mean score'],
          Object.entries(m.noisy.byPolicy).map(([id, p]: [string, any]) => [
            label(s, id),
            pct(p.win),
            `[${pct(p.lo)}, ${pct(p.hi)}]`,
            fx(p.score.mean, 1),
          ]),
        ),
    );
  if (m.matrix.length) {
    P(
      '**2-player head to head (S1).** Row strategy’s win share against the column strategy, both seat orders, 2,000 games per cell (1,000 on the diagonal).',
    );
    P(
      table(
        ['', ...m.matrix.map((r) => r.short)],
        m.matrix.map((r) => [
          `${r.label} (${r.short})`,
          ...r.cells.map((c: any) => (c.v === null ? '—' : pct(c.v, 0))),
        ]),
      ),
    );
  }

  // 3 — seats
  P('## 3. Seat and turn-order advantage');
  P(
    'Seat 1 starts on top of the stack and moves first (R6). Fair share is 1/n. R45: we report the gap both in percentage points and relative to fair share; **pass/fail uses percentage points (±5 pts)**, and the relative reading (±5% of fair share) is shown for reference.',
  );
  for (const x of m.seats)
    P(
      `**${x.players} players** — worst seat gap ${fx(x.worstPP, 1)} pts (${x.passPP ? 'pass' : 'fail'}), ${pct(x.worstRel)} relative (${x.passRel ? 'pass' : 'fail'} on the stricter reading).\n\n` +
        table(
          ['Seat', 'Win rate', '95% CI', 'Fair', 'Gap (pts)', 'Gap (relative)'],
          x.rows.map((r: any) => [
            r.seat,
            pct(r.win),
            `[${pct(r.lo)}, ${pct(r.hi)}]`,
            pct(r.fair),
            `${r.diffPP >= 0 ? '+' : ''}${fx(r.diffPP, 1)}`,
            `${r.diffRel >= 0 ? '+' : ''}${pct(r.diffRel)}`,
          ]),
        ),
    );

  // 4 — scores
  P('## 4. Scores and where they come from');
  for (const n of [4, 3, 2]) {
    const g = s.groups[`main-${n}p`];
    if (!g) continue;
    P(
      `**${n}p:** mean ${fx(g.score.mean, 1)} (sd ${fx(g.score.sd, 1)}). Share of all points: ${Object.entries(
        g.components,
      )
        .map(([k, c]: [string, any]) => `${k.replace('_', ' ')} ${pct(c.share)} (avg ${fx(c.mean, 1)})`)
        .join(', ')}.`,
    );
  }
  if (m.pred)
    P(
      `**What predicts winning (4p).** ${m.pred.method} n = ${m.pred.n.toLocaleString()} player-games.\n\n` +
        table(
          ['Component', 'Logistic β (per sd)', 'Point-biserial r'],
          Object.keys(m.pred.coefficients).map((k) => [
            k.replace('_', ' '),
            fx(m.pred.coefficients[k], 3),
            fx(m.pred.pointBiserial[k], 3),
          ]),
        ) +
        '\n\n`kept` (discs kept) is included as a control: it captures the Doorway tile you ended up with.',
    );

  // 5 — length
  P('## 5. Game length and turn order');
  P(
    table(
      [
        'Players',
        'Turns per game',
        'Turns per player',
        'Extra (back-to-back) turns per player',
        'Share of a player’s turns that were extra',
      ],
      [4, 3, 2]
        .filter((n) => s.groups[`main-${n}p`])
        .map((n) => {
          const g = s.groups[`main-${n}p`];
          return [
            n,
            `${fx(g.turnsPerGame.mean, 1)} (sd ${fx(g.turnsPerGame.sd, 1)})`,
            fx(g.turnsPerPlayer.mean, 1),
            fx(g.extraTurns.mean, 2),
            pct(g.extraTurnShare),
          ];
        }),
    ),
  );
  P(
    'An "extra turn" is a turn taken straight after your own previous turn because you were still furthest back (rulebook §4).',
  );

  // 6 — rush
  P('## 6. Quest vs. Rush');
  if (m.g4)
    P(
      `In 4p, ${pct(m.rushShare)} of moves are Rushes (${fx(m.g4.rushes.mean, 2)} per player per game vs ${fx(m.g4.quests.mean, 1)} quests). An average Rush moves ${fx(m.g4.rushDistance, 2)} spaces and ${pct(m.g4.rushDiscardShare)} of Rushes use the discard.\n\n` +
        table(
          ['Rushes in a game', 'Player-games', 'Win rate', '95% CI', 'Fair'],
          m.rushBuckets.map((b: any) => [
            b.bucket,
            b.n.toLocaleString(),
            pct(b.win),
            `[${pct(b.lo)}, ${pct(b.hi)}]`,
            pct(b.fair),
          ]),
        ),
    );

  // 7 — cards
  P('## 7. Cards');
  P(
    `Pick rate = picks ÷ turns on which the card was face up and takeable by the player to move. "Win when picked" is the average win share of players who took the card, relative to fair share (1 = fair), from S2 + S3 (all strategies, 3–4p). A card is flagged when its 95% CI excludes fair share by more than ${pct(s.cards.margin, 0)} (strong: lower bound > ${fx(1 + s.cards.margin)}; weak: upper bound < ${fx(1 - s.cards.margin)}).`,
  );
  P(
    table(
      ['Card', 'Name', 'Age', 'Yrs', 'Pts', 'Pick rate', 'Win when picked (rel.)', '95% CI', 'Flag'],
      m.cards
        .slice()
        .sort((a: any, b: any) => b.relWin - a.relWin)
        .map((c: any) => [
          c.id,
          c.name,
          c.age,
          c.years,
          c.points,
          pct(c.pickRate),
          fx(c.relWin),
          `[${fx(c.relLo)}, ${fx(c.relHi)}]`,
          c.flag ?? '',
        ]),
    ),
  );

  // 8 — experience
  P('## 8. Experience and engines');
  for (const n of [4, 3, 2]) {
    const g = s.groups[`main-${n}p`];
    if (!g) continue;
    P(
      `**${n}p:** ${fx(g.savedExperience.mean, 2)} years saved by experience and ${fx(g.savedPowers.mean, 2)} by powers per player per game (${fx(g.quests.mean, 1)} quests). Average years paid per quest by quarter of life (0–9, 10–19, 20–29, 30–39): ${g.costByLifeQuarter.map((x: number) => fx(x, 2)).join(' → ')}.`,
    );
  }

  // 9 — powers
  P('## 9. Powers and stale markets');
  if (m.g4) {
    P(
      table(
        ['Power', 'Held per player-game (4p)'],
        Object.entries(m.g4.powersHeldPerPlayer).map(([k, v]: [string, any]) => [k, fx(v, 3)]),
      ),
    );
    P(
      table(
        ['Once-per-game power', 'Players who held it', 'Used it', 'Use rate'],
        Object.entries(m.g4.oncePowerUseRate).map(([k, v]: [string, any]) => [
          k,
          v.held,
          v.used,
          v.rate === null ? '—' : pct(v.rate),
        ]),
      ),
    );
    P(
      `Turns with no takeable quest (stale market): ${fx(m.g4.noQuestTurns.mean, 2)} per player per game in 4p (${pct(m.g4.noQuestShare)} of turns). Swaps: ${m.g4.swaps.made.toLocaleString()} made, ${m.g4.swaps.declined.toLocaleString()} declined, ${m.g4.swaps.auto.toLocaleString()} auto-skipped (R3).`,
    );
  }

  // 10 — sweeps
  P('## 10. Sensitivity sweeps (S4)');
  P(
    'Each value: 10,000 4p (or 3p / 2p) games on a uniform field of the 10 non-random strategies, seats drawn uniformly, same deals for every value (paired). The lookahead seat runs at a reduced budget here (D-SIM-3); S4C re-checks two sweeps with a full-budget lookahead seat in every game.',
  );
  for (const w of m.sweeps)
    P(
      `**${w.key}**\n\n` +
        table(
          [
            'Value',
            'Avg score',
            'Turns',
            'Non-first lost',
            '1st lost',
            'Last lost',
            'Lose any',
            'Top strategy',
            'Top win',
            'Spread',
            'Seat 1 gap (pts)',
            'Full life share',
          ],
          w.values.map((v: any) => [
            `${v.base ? '**' : ''}${v.label}${v.base ? '** (base)' : ''}`,
            fx(v.avgScore, 1),
            fx(v.turns, 1),
            fx(v.nonFirstLost),
            fx(v.firstLost),
            fx(v.lastLost),
            pct(v.shareLostAny),
            label(s, v.topPolicy),
            pct(v.topWin),
            pct(v.spread),
            fx(v.seat1PP, 1),
            pct(v.fullLifeShare),
          ]),
        ),
    );
  for (const c of m.confirm)
    P(
      `**Confirmation with lookahead — ${c.key} (S4C)**\n\n` +
        table(
          ['Value', 'Games', 'Lookahead win', '95% CI', 'Non-first lost', 'Top strategy'],
          c.values.map((v: any) => [
            `${v.label}${v.base ? ' (base)' : ''}`,
            v.games,
            pct(v.lookahead?.win),
            `[${pct(v.lookahead?.lo)}, ${pct(v.lookahead?.hi)}]`,
            fx(v.nonFirstLost),
            label(s, v.topPolicy),
          ]),
        ),
    );

  // 11 — tweaks
  P('## 11. Suggested rule tweaks');
  P(
    'Suggestions only — the default ruleset is unchanged. Each cites the sweep row that backs it; try them in `/designer` → Sandbox.',
  );
  P(
    m.tweaks.length
      ? m.tweaks.map((t, i) => `${i + 1}. **${t.title}.** ${t.why}\n   _Evidence:_ ${t.evidence}`).join('\n')
      : '_No sweep value improved on the baseline by the stated margins._',
  );

  // 12 — ready to print
  P('## 12. "Ready to print" signals');
  P(
    table(
      ['Signal', 'Target', 'Measured', 'Verdict'],
      m.readyToPrint.map((r) => [
        r.signal,
        r.target,
        r.value,
        r.verdict === 'pass' ? '**pass**' : r.verdict === 'fail' ? '**fail**' : 'n/a (human playtests)',
      ]),
    ),
  );

  // solo
  if (m.solo.length) {
    P('## Solo challenge (S5)');
    P(
      table(
        [
          'Strategy',
          'Mean score (sd)',
          'A quiet life',
          'A good life',
          'A full life',
          'Everything you could bring',
        ],
        m.solo.map((x: any) => [
          x.label,
          `${fx(x.score.mean, 1)} (${fx(x.score.sd, 1)})`,
          pct(x.ratings['A quiet life']),
          pct(x.ratings['A good life']),
          pct(x.ratings['A full life']),
          pct(x.ratings['Everything you could bring']),
        ]),
      ),
    );
  }
  P('## Method notes');
  P(
    [
      '- Bots: `packages/bots/strategies.json`. Weighted scorers use the features in `packages/bots/src/features.ts`. `lookahead` is determinized Monte Carlo (16 determinizations × ≤ 6 candidate moves, greedy rollouts; S4 field uses 4 × 5).',
      '- Every bot picks its Doorway window optimally (spec §6), so discs lost here are the minimum possible for each tower.',
      '- Seeds are fixed (`doorway-2026-*`); rerunning `pnpm sim:study` reproduces every number. Raw runs live in `reports/runs/` (gitignored); `reports/data/` holds the aggregated CSVs, Parquet copies and a 1,000-game move-log sample.',
      '- Win rates count a k-way shared win as 1/k (R28).',
    ].join('\n'),
  );
  return out.join('\n');
}

export function answers(m: Model) {
  const a: { q: string; a: string; chip: string }[] = [];
  const d4 = m.d4;
  if (d4) {
    const first = d4.rows[0];
    const last = d4.rows[d4.rows.length - 1];
    a.push({
      q: 'Does arriving first make the Doorway irrelevant?',
      a:
        first && first.lost >= 1
          ? `No. Even the first player through loses ${fx(first.lost, 1)} discs on average in 4p (tower ${fx(first.tower, 1)} vs a tile of ${fx(first.allowance, 1)}); the last loses ${fx(last.lost, 1)}. ${pct(d4.shareLostAny, 0)} of all arrivals leave something behind, so choosing the stretch matters for everyone.`
          : `Partly. First arrivals lose only ${fx(first?.lost, 1)} discs in 4p while the last lose ${fx(last?.lost, 1)}.`,
      chip: 'HEADLINE',
    });
  }
  if (m.top4)
    a.push({
      q: 'Does any strategy dominate?',
      a: m.topArch4
        ? `${m.topArch4.win <= TARGETS.maxStrategyWin4p ? 'No archetype does.' : 'Yes.'} The best 4p archetype (${m.topArch4.label}) wins ${pct(m.topArch4.win)} [${pct(m.topArch4.lo)}, ${pct(m.topArch4.hi)}] against a 35% ceiling; the weakest wins ${pct(m.strat4.filter((x) => x.id !== 'random' && x.id !== 'lookahead').slice(-1)[0]?.win)}.${m.look4 ? ` The lookahead search bot wins ${pct(m.look4.win)}${m.look4.win > TARGETS.maxStrategyWin4p ? ', just over the ceiling — skilful play is rewarded, mostly by Rushing more (' + fx(m.look4.rushes, 1) + ' per game) and arriving earlier' : ''}.` : ''}`
        : `The best 4p strategy (${m.top4.label}) wins ${pct(m.top4.win)}.`,
      chip: 'BALANCE',
    });
  const s4 = m.seats.find((x) => x.players === 4);
  if (s4) {
    const r1 = s4.rows[0];
    a.push({
      q: 'Is there a seat advantage?',
      a: `${Math.abs(r1.diffPP) <= TARGETS.seatPP ? 'Small.' : 'Yes.'} The top of the starting stack wins ${pct(r1.win)} in 4p vs a fair ${pct(r1.fair)} (${r1.diffPP >= 0 ? '+' : ''}${fx(r1.diffPP, 1)} pts). Worst seat gap by player count: ${m.seats.map((x) => `${x.players}p ${fx(x.worstPP, 1)} pts`).join(', ')}.`,
      chip: 'SEATS',
    });
  }
  if (m.noRush && m.manyRush)
    a.push({
      q: 'Is Rush worth it?',
      a: `Rarely, as the bots play it: ${pct(m.rushShare)} of 4p moves are Rushes. Players who never rush win ${pct(m.noRush.win)} (fair ${pct(m.noRush.fair)}); players who rush 3+ times win ${pct(m.manyRush.win)}.`,
      chip: 'TEMPO',
    });
  const comps = m.components.filter((c) => c.share !== undefined);
  if (comps.length)
    a.push({
      q: 'Where do the points come from?',
      a: `${comps.map((c) => `${c.name} ${pct(c.share, 0)}`).join(', ')} of all 4p points. ${
        m.pred
          ? `The strongest predictor of winning (standardized logistic β) is ${Object.entries(
              m.pred.coefficients,
            )
              .filter(([k]) => k !== 'kept')
              .sort((x: any, y: any) => y[1] - x[1])[0][0]
              .replace('_', ' ')}.`
          : ''
      }`,
      chip: 'SCORING',
    });
  if (m.g4)
    a.push({
      q: 'How long is a game?',
      a: `${fx(m.g4.turnsPerGame.mean, 0)} turns in 4p (${fx(m.g4.turnsPerPlayer.mean, 1)} per player), of which ${fx(m.g4.extraTurns.mean, 1)} per player are back-to-back extra turns from the furthest-back rule.`,
      chip: 'LENGTH',
    });
  if (m.flagged.length || m.unused.length)
    a.push({
      q: 'Any cards out of line?',
      a: `${
        m.flagged.length
          ? `${m.flagged.length} of 60 are flagged at ±10%. Strongest: ` +
            m.flagged
              .slice(0, 5)
              .map((c: any) => `${c.name} (${c.id}, ${c.flag}, ${fx(c.relWin)}× fair)`)
              .join('; ')
          : 'No card is flagged at the ±10% margin'
      }.${m.unused.length ? ` Rarely picked: ${m.unused.map((c: any) => c.name).join(', ')}.` : ''}`,
      chip: 'CARDS',
    });
  return a;
}

function headline(m: Model): string {
  const lines: string[] = [];
  const d4 = m.d4;
  if (!d4) return 'No 4p data.';
  const first = d4.rows[0];
  const irrelevant = first.lost < 0.5 && first.shareLostAny < 0.25;
  if (irrelevant) {
    lines.push(
      `**Short answer: for the first arrival, largely yes.** In 4p the first player through brings ${fx(first.tower, 1)} discs to a tile of ${fx(first.allowance, 1)} and loses only ${fx(first.lost, 1)} on average; later arrivals lose more (${d4.rows.map((r: any) => fx(r.lost, 1)).join(' / ')}).`,
    );
    return lines.join('\n\n');
  }
  lines.push(
    `**Short answer: no.** Towers grow far taller than any Doorway tile. In 4p the first arrival brings a tower of ${fx(first.tower, 1)} to a tile of ${fx(first.allowance, 1)} and still leaves ${fx(first.lost, 1)} discs behind (${pct(first.shareLostAny, 0)} of first arrivals lose at least one). Later arrivals lose more because their tiles are smaller, not because their towers are taller.`,
  );
  lines.push(
    `So the Doorway decision is real for every player, including the first one; arriving first buys you a bigger window (+${fx(d4.rows[0].allowance - d4.rows[d4.rows.length - 1].allowance, 0)} discs over last place) rather than "keep everything". The risk the rulebook flags (§13 "Doorway irrelevance") does not show up with these bots. The S4 sweep below shows how the gap between first and last moves with other tile sets.`,
  );
  return lines.join('\n\n');
}
